/**
 * Builds the three artifacts and the backend's served copy:
 *   dist/slack-start.js  IIFE, auto-binds [data-agentweb-slack-start] (script tag)
 *   dist/index.mjs       ESM core (mountSlackStart/autoBind/openSlackStart)
 *   dist/react.mjs       ESM React adapter (react external, peer dependency)
 *   ../../backend/src/embed/slackStartBundle.generated.ts
 *       the IIFE as a string constant, so tsc ships it in backend/dist (the EB bundle
 *       contains only dist + package.json — a plain .js asset would 404 in production;
 *       same reason as src/sdk/awSdkSource.ts).
 *
 * --check-embed: rebuild and fail if the committed generated file is stale.
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const generated = resolve(root, '../../backend/src/embed/slackStartBundle.generated.ts');
const checkOnly = process.argv.includes('--check-embed');

const common = {
  bundle: true,
  minify: true,
  target: ['es2018'],
  jsx: 'automatic',
  jsxImportSource: 'preact',
  legalComments: 'none',
  logLevel: 'warning',
  write: false,
};

const [iife, esm, react] = await Promise.all([
  build({ ...common, entryPoints: [resolve(root, 'src/embed.ts')], format: 'iife' }),
  build({ ...common, entryPoints: [resolve(root, 'src/index.ts')], format: 'esm' }),
  build({ ...common, entryPoints: [resolve(root, 'src/react.ts')], format: 'esm', external: ['react'] }),
]);

const bundle = iife.outputFiles[0].text;
const sha256 = createHash('sha256').update(bundle).digest('hex');
const tsSource =
  `/* eslint-disable */\n` +
  `// GENERATED by packages/slack-start (npm run build). Do not edit by hand.\n` +
  `// ENG-2782: served at GET /embed/slack-start.js (routes/slackStartEmbed.ts).\n` +
  `export const SLACK_START_BUNDLE_SHA256 = ${JSON.stringify(sha256)};\n` +
  `export const SLACK_START_BUNDLE: string = ${JSON.stringify(bundle)};\n`;

if (checkOnly) {
  const current = existsSync(generated) ? readFileSync(generated, 'utf8') : '';
  if (current !== tsSource) {
    console.error(`slack-start: ${generated} is stale — run \`npm run build\` in packages/slack-start and commit it.`);
    process.exit(1);
  }
  console.log(`slack-start: backend embed is current (sha256 ${sha256.slice(0, 12)})`);
} else {
  mkdirSync(resolve(root, 'dist'), { recursive: true });
  writeFileSync(resolve(root, 'dist/slack-start.js'), bundle);
  writeFileSync(resolve(root, 'dist/index.mjs'), esm.outputFiles[0].text);
  writeFileSync(resolve(root, 'dist/react.mjs'), react.outputFiles[0].text);
  mkdirSync(dirname(generated), { recursive: true });
  writeFileSync(generated, tsSource);
  console.log(`slack-start: built dist/ and backend embed (sha256 ${sha256.slice(0, 12)})`);
}
