import { getSecret } from "../utils/secretsManager";
import { uploadFileToS3 } from "../utils/s3Utils";
import axios from "axios";

interface DeepResearchResult {
  success: boolean;
  htmlContent?: string;
  markdownContent?: string;  // Raw markdown for blog integration
  title?: string;            // Extracted title for blog
  imagePlaceholders?: Array<{
    key: string;
    imagePrompt: string;
    context: string;
    imageUrl?: string;
    source?: 'generated' | 'web';
  }>;
  researchSummary?: string;
  imagesGenerated?: number;
  imagesFromWeb?: number;
  error?: string;
}

interface DeepResearchParams {
  topic: string;
  prompt?: string;
  userId: string;
  rawMarkdownOnly?: boolean;  // When true, skip image processing and return raw markdown
}

interface ImageDecision {
  key: string;
  context: string;
  decision: 'generate' | 'search';
  prompt: string;
  searchQuery?: string;
}

export class DeepResearchService {
  private geminiApiKey: string | null = null;
  private geminiApiKeyPromise: Promise<string> | null = null;

  constructor() {
    // API key will be lazy-loaded from secrets manager
  }

  /**
   * Get the Gemini API key from Secrets Manager (lazy-loaded)
   */
  private async getGeminiApiKey(): Promise<string> {
    // Return cached key if available
    if (this.geminiApiKey) {
      return this.geminiApiKey;
    }

    // If already loading, wait for that promise
    if (this.geminiApiKeyPromise) {
      return this.geminiApiKeyPromise;
    }

    // Load the API key
    this.geminiApiKeyPromise = (async () => {
      try {
        const environment = process.env.NODE_ENV === 'production' ? 'prod' : 'dev';
        const secretName = `${environment}/AgentWeb/GeminiAPIKey`;
        const apiKey = await getSecret(secretName);

        if (!apiKey || !apiKey.trim()) {
          throw new Error('Gemini API key is empty');
        }

        this.geminiApiKey = apiKey.trim();
        return this.geminiApiKey;
      } catch (error) {
        console.error('Error getting Gemini API key:', error);
        this.geminiApiKeyPromise = null; // Reset promise on error
        throw error;
      }
    })();

    return this.geminiApiKeyPromise;
  }

  /**
   * Use LLM to decide whether to generate or search for each image
   */
  private async decideImageSources(
    placeholders: Array<{ key: string; imagePrompt: string; context: string }>,
    topic: string
  ): Promise<ImageDecision[]> {
    try {
      const { GoogleGenAI } = require('@google/genai');
      const apiKey = await this.getGeminiApiKey();
      const ai = new GoogleGenAI({ apiKey });

      const decisions: ImageDecision[] = [];

      for (const placeholder of placeholders) {
        try {
          // Ask LLM to decide
          const decisionPrompt = `You are deciding how to get an image for a research report.

Topic: "${topic}"
Section: "${placeholder.context}"
Image Purpose: "${placeholder.imagePrompt}"

Should this image be:
A) GENERATED by AI - best for: infographics, diagrams, conceptual illustrations, abstract visuals, custom graphics
B) SEARCHED from web - best for: real photographs, historical images, logos, screenshots, product images, famous people/places

Respond with ONLY a JSON object (no markdown, no code blocks):
{"decision": "generate" or "search", "reason": "brief reason", "searchQuery": "search query if search, empty if generate"}`;

          const response = await ai.models.generateContent({
            model: 'gemini-2.5-flash',
            contents: decisionPrompt,
          });

          const responseText = response.text || '';
          
          // Parse the JSON response
          let decision: 'generate' | 'search' = 'generate';
          let searchQuery = '';
          
          try {
            // Try to extract JSON from the response
            const jsonMatch = responseText.match(/\{[\s\S]*\}/);
            if (jsonMatch) {
              const parsed = JSON.parse(jsonMatch[0]);
              decision = parsed.decision === 'search' ? 'search' : 'generate';
              searchQuery = parsed.searchQuery || `${placeholder.context} ${topic} image`;
            }
          } catch (parseError) {
            // Default to generate if parsing fails
            console.warn(`Failed to parse LLM decision, defaulting to generate:`, parseError);
          }

          decisions.push({
            key: placeholder.key,
            context: placeholder.context,
            decision,
            prompt: placeholder.imagePrompt,
            searchQuery: decision === 'search' ? searchQuery : undefined
          });

          console.log(`Image decision for "${placeholder.context}": ${decision}`);

        } catch (error) {
          // Default to generate on error
          console.error(`Error deciding for ${placeholder.key}, defaulting to generate:`, error);
          decisions.push({
            key: placeholder.key,
            context: placeholder.context,
            decision: 'generate',
            prompt: placeholder.imagePrompt
          });
        }
      }

      return decisions;
    } catch (error) {
      console.error('Error in decideImageSources:', error);
      // Return all as generate on major error
      return placeholders.map(p => ({
        key: p.key,
        context: p.context,
        decision: 'generate' as const,
        prompt: p.imagePrompt
      }));
    }
  }

  /**
   * Generate an image using AI
   */
  private async generateImage(prompt: string, filename: string, userId: string): Promise<string | null> {
    try {
      const { imageService } = await import('./imageGeneration');
      
      const result = await imageService.generateImage({
        prompt,
        filename,
        userId,
        imageModel: 'gemini-3-pro-image-preview',
        quality: 'medium'
      });

      if (result.success && result.imageUrl) {
        return result.imageUrl;
      }
      
      console.error('Image generation failed:', result.error);
      return null;
    } catch (error) {
      console.error('Error generating image:', error);
      return null;
    }
  }

  /**
   * Search for an image on the web and download it
   */
  private async searchAndDownloadImage(searchQuery: string, userId: string, filename: string): Promise<string | null> {
    try {
      // Use Google Custom Search API or fallback to a simple image search
      // For now, we'll use a web search and try to find image URLs
      
      const searchUrl = `https://www.googleapis.com/customsearch/v1?key=${process.env.GOOGLE_SEARCH_API_KEY}&cx=${process.env.GOOGLE_SEARCH_CX}&q=${encodeURIComponent(searchQuery)}&searchType=image&num=3&safe=active`;
      
      try {
        const searchResponse = await axios.get<{ items?: Array<{ link: string }> }>(searchUrl, { timeout: 10000 });
        
        if (searchResponse.data?.items && searchResponse.data.items.length > 0) {
          // Try to download the first available image
          for (const item of searchResponse.data.items) {
            const imageUrl = item.link;
            try {
              const downloadedUrl = await this.downloadAndUploadImage(imageUrl, userId, filename);
              if (downloadedUrl) {
                return downloadedUrl;
              }
            } catch (downloadError) {
              console.warn(`Failed to download image from ${imageUrl}:`, downloadError);
              continue;
            }
          }
        }
      } catch (searchError: any) {
        // If Google Search API is not configured, try Unsplash as fallback
        console.warn('Google Image Search failed, trying Unsplash fallback:', searchError.message);
        return await this.searchUnsplash(searchQuery, userId, filename);
      }

      return null;
    } catch (error) {
      console.error('Error searching for image:', error);
      return null;
    }
  }

  /**
   * Fallback: Search Unsplash for free images
   */
  private async searchUnsplash(query: string, userId: string, filename: string): Promise<string | null> {
    try {
      // Use Unsplash Source API (no API key required for random images)
      const unsplashUrl = `https://source.unsplash.com/800x600/?${encodeURIComponent(query)}`;
      
      // Follow redirect to get actual image
      const response = await axios.get<ArrayBuffer>(unsplashUrl, {
        responseType: 'arraybuffer',
        timeout: 15000
      });

      if (response.data) {
        const imageBuffer = Buffer.from(response.data as ArrayBuffer);
        const uploadResult = await uploadFileToS3(
          imageBuffer,
          filename,
          userId,
          'image/jpeg'
        );

        if (uploadResult.success && uploadResult.url) {
          return uploadResult.url;
        }
      }

      return null;
    } catch (error) {
      console.error('Unsplash search failed:', error);
      return null;
    }
  }

  /**
   * Download an image from URL and upload to S3
   */
  private async downloadAndUploadImage(imageUrl: string, userId: string, filename: string): Promise<string | null> {
    try {
      const response = await axios.get<ArrayBuffer>(imageUrl, {
        responseType: 'arraybuffer',
        timeout: 15000,
        headers: {
          'User-Agent': 'Mozilla/5.0 (compatible; AgentWeb/1.0)'
        }
      });

      const contentType = (response.headers['content-type'] as string) || 'image/jpeg';
      const imageBuffer = Buffer.from(response.data as ArrayBuffer);

      const uploadResult = await uploadFileToS3(
        imageBuffer,
        filename,
        userId,
        contentType
      );

      if (uploadResult.success && uploadResult.url) {
        return uploadResult.url;
      }

      return null;
    } catch (error) {
      console.error('Error downloading image:', error);
      return null;
    }
  }

  /**
   * Process all images for a research report
   */
  private async processImages(
    decisions: ImageDecision[],
    userId: string
  ): Promise<Map<string, { url: string; source: 'generated' | 'web' }>> {
    const imageResults = new Map<string, { url: string; source: 'generated' | 'web' }>();

    // Process images in parallel (max 3 at a time)
    const batchSize = 3;
    for (let i = 0; i < decisions.length; i += batchSize) {
      const batch = decisions.slice(i, i + batchSize);
      
      const results = await Promise.all(
        batch.map(async (decision, batchIndex) => {
          const filename = `research-img-${Date.now()}-${i + batchIndex}.png`;
          let imageUrl: string | null = null;
          let source: 'generated' | 'web' = 'generated';

          if (decision.decision === 'generate') {
            console.log(`Generating image for: ${decision.context}`);
            imageUrl = await this.generateImage(decision.prompt, filename, userId);
            source = 'generated';
          } else {
            console.log(`Searching web for: ${decision.searchQuery}`);
            imageUrl = await this.searchAndDownloadImage(
              decision.searchQuery || decision.context,
              userId,
              filename
            );
            source = 'web';

            // Fallback to generation if web search fails
            if (!imageUrl) {
              console.log(`Web search failed, falling back to generation for: ${decision.context}`);
              imageUrl = await this.generateImage(decision.prompt, filename, userId);
              source = 'generated';
            }
          }

          return { key: decision.key, url: imageUrl, source };
        })
      );

      for (const result of results) {
        if (result.url) {
          imageResults.set(result.key, { url: result.url, source: result.source });
        }
      }
    }

    return imageResults;
  }

  /**
   * Replace placeholders in HTML with actual images
   */
  private replaceImagePlaceholders(
    htmlContent: string,
    imageResults: Map<string, { url: string; source: 'generated' | 'web' }>
  ): string {
    let updatedHtml = htmlContent;

    for (const [key, { url }] of imageResults) {
      const placeholder = `<!--${key}-->`;
      const imgTag = `<div class="research-image"><img src="${url}" alt="${key}" style="max-width: 100%; height: auto; border-radius: 8px; margin: 1rem 0;"></div>`;
      updatedHtml = updatedHtml.replace(placeholder, imgTag);
    }

    return updatedHtml;
  }

  /**
   * Perform deep research on a topic using Gemini Deep Research Agent
   */
  async performDeepResearch(params: DeepResearchParams): Promise<DeepResearchResult> {
    try {
      const { GoogleGenAI } = require('@google/genai');
      
      const apiKey = await this.getGeminiApiKey();
      const ai = new GoogleGenAI({ apiKey });

      // Build the research prompt
      const researchInput = params.prompt 
        ? `${params.topic}\n\nAdditional instructions: ${params.prompt}`
        : params.topic;

      console.log(`Starting deep research on topic: "${params.topic}"`);

      // Start the Deep Research Agent with background=true for async execution
      const initialInteraction = await ai.interactions.create({
        input: researchInput,
        agent: 'deep-research-pro-preview-12-2025',
        background: true,
      });

      console.log(`Deep research started. Interaction ID: ${initialInteraction.id}`);

      // Poll for results
      const maxPollAttempts = 120; // 20 minutes max (120 * 10 seconds)
      let pollAttempts = 0;
      let interaction = initialInteraction;

      while (interaction.status !== 'completed' && pollAttempts < maxPollAttempts) {
        console.log(`Deep research status: ${interaction.status} (attempt ${pollAttempts + 1}/${maxPollAttempts})`);
        
        // Wait 10 seconds before polling again
        await new Promise(resolve => setTimeout(resolve, 10000));
        
        // Get updated interaction status
        interaction = await ai.interactions.get(initialInteraction.id);
        pollAttempts++;

        // Check for failure states
        if (interaction.status === 'failed' || interaction.status === 'cancelled') {
          console.error(`Deep research ${interaction.status}`);
          return {
            success: false,
            error: `Deep research ${interaction.status}. Please try again.`
          };
        }
      }

      if (interaction.status !== 'completed') {
        return {
          success: false,
          error: 'Deep research timed out after 20 minutes. Please try again with a more specific topic.'
        };
      }

      console.log('Deep research completed successfully');

      // Extract the research report from the interaction outputs
      const outputs = interaction.outputs || [];
      if (outputs.length === 0) {
        return {
          success: false,
          error: 'Deep research completed but no output was returned.'
        };
      }

      // Get the final text output (usually the last one)
      const finalOutput = outputs[outputs.length - 1];
      const researchText = finalOutput.text || '';

      if (!researchText) {
        return {
          success: false,
          error: 'Deep research completed but the research report is empty.'
        };
      }

      // If rawMarkdownOnly, return the markdown without image processing
      if (params.rawMarkdownOnly) {
        console.log('Returning raw markdown (rawMarkdownOnly mode)');
        
        // Extract title from first H1 or first line
        const titleMatch = researchText.match(/^#\s+(.+)$/m);
        const title = titleMatch 
          ? titleMatch[1].trim() 
          : researchText.split('\n')[0].replace(/^#+\s*/, '').trim() || params.topic;
        
        // Create summary from first 500 chars
        const cleanText = researchText.replace(/[#*\-]/g, '').trim();
        const summary = cleanText.length > 500 
          ? cleanText.substring(0, 500) + '...'
          : cleanText;

        return {
          success: true,
          markdownContent: researchText,
          title,
          researchSummary: summary
        };
      }

      // Post-process the research to create HTML with image placeholders
      console.log('Processing research output and extracting image placeholders...');
      const processedResult = this.processResearchOutput(researchText, params.topic);

      // Decide image sources using LLM
      console.log(`Deciding image sources for ${processedResult.imagePlaceholders.length} placeholders...`);
      const imageDecisions = await this.decideImageSources(
        processedResult.imagePlaceholders,
        params.topic
      );

      // Process images (generate or search)
      console.log('Processing images...');
      const imageResults = await this.processImages(imageDecisions, params.userId);

      // Count sources
      let imagesGenerated = 0;
      let imagesFromWeb = 0;
      for (const { source } of imageResults.values()) {
        if (source === 'generated') imagesGenerated++;
        else imagesFromWeb++;
      }

      // Replace placeholders with actual images
      const htmlWithImages = this.replaceImagePlaceholders(processedResult.htmlContent, imageResults);

      // Upload the final HTML to S3
      const htmlBuffer = Buffer.from(htmlWithImages, 'utf-8');
      const filename = `deep-research-${Date.now()}.html`;
      
      const uploadResult = await uploadFileToS3(
        htmlBuffer,
        filename,
        params.userId,
        'text/html'
      );

      // Update placeholders with image URLs
      const finalPlaceholders = processedResult.imagePlaceholders.map(p => {
        const result = imageResults.get(p.key);
        return {
          ...p,
          imageUrl: result?.url,
          source: result?.source
        };
      });

      if (uploadResult.success && uploadResult.url) {
        return {
          success: true,
          htmlContent: uploadResult.url,
          imagePlaceholders: finalPlaceholders,
          researchSummary: processedResult.summary,
          imagesGenerated,
          imagesFromWeb
        };
      }

      // If upload fails, return the raw HTML content
      return {
        success: true,
        htmlContent: htmlWithImages,
        imagePlaceholders: finalPlaceholders,
        researchSummary: processedResult.summary,
        imagesGenerated,
        imagesFromWeb
      };

    } catch (error: any) {
      console.error('Deep research error:', error);
      
      // Handle specific errors
      if (error.message?.includes('interactions')) {
        return {
          success: false,
          error: 'The Gemini Deep Research API is not available. Please ensure you have access to the preview feature.'
        };
      }

      return {
        success: false,
        error: `Deep research failed: ${error.message || 'Unknown error'}`
      };
    }
  }

  /**
   * Process the research output to create HTML with image placeholders and prompts
   */
  private processResearchOutput(researchText: string, topic: string): {
    htmlContent: string;
    imagePlaceholders: Array<{ key: string; imagePrompt: string; context: string }>;
    summary: string;
  } {
    const imagePlaceholders: Array<{ key: string; imagePrompt: string; context: string }> = [];
    let placeholderCount = 0;

    // Convert markdown-style headers and formatting to HTML
    let htmlContent = researchText
      // Convert markdown headers
      .replace(/^### (.+)$/gm, '<h3>$1</h3>')
      .replace(/^## (.+)$/gm, '<h2>$1</h2>')
      .replace(/^# (.+)$/gm, '<h1>$1</h1>')
      // Convert bold
      .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
      // Convert italic
      .replace(/\*(.+?)\*/g, '<em>$1</em>')
      // Convert bullet points
      .replace(/^- (.+)$/gm, '<li>$1</li>')
      // Wrap consecutive list items
      .replace(/(<li>.*<\/li>\n?)+/g, '<ul>$&</ul>')
      // Convert numbered lists
      .replace(/^\d+\. (.+)$/gm, '<li>$1</li>')
      // Convert paragraphs (double newlines)
      .replace(/\n\n/g, '</p><p>')
      // Convert single newlines within paragraphs
      .replace(/\n/g, '<br>');

    // Wrap in paragraph tags
    htmlContent = `<p>${htmlContent}</p>`;

    // Find sections that would benefit from images
    // Look for key sections like introduction, key findings, etc.
    const sectionPatterns = [
      { pattern: /<h2>([^<]+)<\/h2>/gi, type: 'section' },
      { pattern: /<h1>([^<]+)<\/h1>/gi, type: 'main' },
    ];

    // Insert image placeholders after major sections
    for (const { pattern, type } of sectionPatterns) {
      htmlContent = htmlContent.replace(pattern, (match, sectionTitle) => {
        placeholderCount++;
        const key = `IMAGE_PLACEHOLDER_${placeholderCount}`;
        
        // Generate an image prompt based on the section
        const imagePrompt = this.generateImagePrompt(sectionTitle, topic, type);
        
        imagePlaceholders.push({
          key,
          imagePrompt,
          context: sectionTitle
        });

        // Insert placeholder after the heading
        return `${match}\n<!--${key}-->\n`;
      });
    }

    // Generate a summary (first 500 characters of cleaned text)
    const cleanText = researchText.replace(/[#*\-]/g, '').trim();
    const summary = cleanText.length > 500 
      ? cleanText.substring(0, 500) + '...'
      : cleanText;

    // Wrap in a complete HTML document
    const fullHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Deep Research: ${topic}</title>
  <style>
    body {
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Oxygen, Ubuntu, sans-serif;
      line-height: 1.6;
      max-width: 900px;
      margin: 0 auto;
      padding: 2rem;
      color: #333;
    }
    h1, h2, h3 { color: #1a1a2e; margin-top: 2rem; }
    h1 { font-size: 2rem; border-bottom: 2px solid #4a6fa5; padding-bottom: 0.5rem; }
    h2 { font-size: 1.5rem; color: #4a6fa5; }
    h3 { font-size: 1.2rem; }
    ul { padding-left: 1.5rem; }
    li { margin-bottom: 0.5rem; }
    p { margin-bottom: 1rem; }
    .research-image {
      margin: 1.5rem 0;
      text-align: center;
    }
    .research-image img {
      max-width: 100%;
      height: auto;
      border-radius: 8px;
      box-shadow: 0 2px 8px rgba(0,0,0,0.1);
    }
    .image-placeholder {
      background: #f0f4f8;
      border: 2px dashed #4a6fa5;
      border-radius: 8px;
      padding: 2rem;
      text-align: center;
      color: #666;
      margin: 1.5rem 0;
    }
  </style>
</head>
<body>
  <h1>Deep Research: ${topic}</h1>
  ${htmlContent}
</body>
</html>`;

    return {
      htmlContent: fullHtml,
      imagePlaceholders,
      summary
    };
  }

  /**
   * Generate an image prompt based on section context
   */
  private generateImagePrompt(sectionTitle: string, topic: string, type: string): string {
    // Clean up the section title
    const cleanTitle = sectionTitle.replace(/[^\w\s]/g, '').trim();
    
    if (type === 'main') {
      return `Professional infographic illustration about "${topic}". Modern, clean design with visual elements representing key concepts. Corporate style, vibrant colors, white background.`;
    }
    
    return `Illustrative diagram or visual representation for "${cleanTitle}" in the context of "${topic}". Professional style, clear and informative, suitable for a research report.`;
  }

  /**
   * Check if the Deep Research service is available
   */
  async isAvailable(): Promise<boolean> {
    try {
      await this.getGeminiApiKey();
      return true;
    } catch (error) {
      console.warn('Deep Research service not available:', error);
      return false;
    }
  }
}

// Create a singleton instance
let deepResearchService: DeepResearchService;

try {
  deepResearchService = new DeepResearchService();
  console.log('✅ Deep Research Service initialized successfully');
} catch (error) {
  console.warn('⚠️ Failed to initialize Deep Research Service, creating fallback service');
  
  // Create a fallback service that always returns false for isAvailable
  deepResearchService = {
    isAvailable: async () => false,
    performDeepResearch: async () => ({ success: false, error: 'Service not available' })
  } as any;
}

export { deepResearchService };
