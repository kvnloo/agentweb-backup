import { chatbotDb, ChatSession } from "./chatbotService";
import { detectFalseCompletionClaim, ExecutedToolCall, assetProducingToolsInPlay } from "./agentMode/core/synthesisResidue";
import { meteringFeature } from "./llmUsageAttributionService";
import { extractScheduleId } from "../utils/schedulePublishApproval";
import type { LLMUsageContext } from "../utils/llmService";

const SUMMARY_MODEL = "gemini-3.1-flash-lite";
const MAX_MESSAGES_FOR_SUMMARY = 50;
const MIN_USER_MESSAGES = 1;
const SUMMARY_TIMEOUT_MS = 20000;

const SUMMARY_SYSTEM_PROMPT = `You are an expert at summarizing what was accomplished in AI-assisted work sessions.
Analyze the conversation and write a concise 1-2 sentence summary of what was achieved or attempted.

Focus on:
- Concrete outputs produced (e.g. blog posts written, social media posts created, emails sent, reports generated)
- Actions taken on behalf of the user (e.g. leads researched, content published, outreach performed)
- Goals that were successfully completed vs attempted but not completed

Be specific and factual. Use past tense. Do not mention the AI or assistant — describe outcomes from the user's perspective.
Example: "Created 3 LinkedIn posts for a product launch campaign and published them to the company profile."
Example: "Generated a market research report on SaaS pricing trends and exported it as a PDF."

Respond with ONLY valid JSON: {"summary": "<1-2 sentence summary>"}`;

export async function summarizeSession(
  messages: Array<{ role: string; content: string }>,
  currentMessageCount: number,
  usageContext?: LLMUsageContext
): Promise<{ summary: string; evaluatedMessageIndex: number }> {
  const recentMessages = messages.slice(-MAX_MESSAGES_FOR_SUMMARY);
  const conversationText = recentMessages
    .map((m) => `${m.role}: ${typeof m.content === "string" ? m.content : JSON.stringify(m.content)}`)
    .join("\n");

  const { agentModeService } = await import("./agentModeService");

  const llmPromise = agentModeService.callLLM(
    SUMMARY_MODEL,
    [
      { role: "system", content: SUMMARY_SYSTEM_PROMPT },
      { role: "user", content: `Summarize what was achieved in this session:\n\n${conversationText}` },
    ],
    {
      temperature: 0,
      max_completion_tokens: 200,
      response_format: { type: "json_object" },
      taskClass: 'nonstandard_consumer',
      // ENG-1858: summarizing the user's own session — attribute it to them.
      usageContext: usageContext ?? { feature: "session_summary" },
    }
  );

  const timeoutPromise = new Promise<never>((_, reject) =>
    setTimeout(() => reject(new Error("Summary LLM call timed out")), SUMMARY_TIMEOUT_MS)
  );

  const res = await Promise.race([llmPromise, timeoutPromise]);

  const raw = res.choices?.[0]?.message?.content ?? "{}";
  const parsed = JSON.parse(raw);

  return {
    summary: parsed.summary || "Session completed.",
    evaluatedMessageIndex: currentMessageCount,
  };
}

// ENG-1331 follow-up: found live-testing the ENG-1331 fix on production. This
// summary is generated by a free-text LLM call (`summarizeSession` below) that
// only reads the transcript prose — it has no access to the tool-call ledger, so
// it can hallucinate completion the same way a fluent final synthesis can (the
// exact defect ENG-1331 fixed for the chat's own closing message). Observed live:
// re-summarizing mid-run (this is called from `getSessions`' background refresh,
// with no concept of "still in progress") claimed "rendered all 12 sizes...
// completed QA and a final contact sheet" while only ~10 of 12 existed and the
// work-plan step was still `pending`. That text is served verbatim by the
// `account_summary` Emma tool, so a user asking "what have you gotten done"
// mid-run would be told a false completion — same customer-facing harm, a
// different generator. Ground it the same way: flatten every turn's persisted
// `metadata.toolCalls` ledger and re-run the ENG-1331 claim check against it.
function flattenSessionToolCalls(messages: ChatSession["messages"]): ExecutedToolCall[] {
  const flat: ExecutedToolCall[] = [];
  for (const message of messages || []) {
    if ((message as any)?.role !== "assistant") continue;
    const toolCalls = (message as any)?.metadata?.toolCalls;
    if (Array.isArray(toolCalls)) flat.push(...toolCalls);
  }
  return flat;
}

export async function summarizeSessionIfNeeded(
  session: ChatSession
): Promise<NonNullable<ChatSession["sessionSummary"]> | null> {
  const messageCount = session.messageCount ?? session.messages?.length ?? 0;

  // Skip if already summarized and up-to-date
  if (
    session.sessionSummary &&
    session.sessionSummary.evaluatedMessageIndex >= messageCount
  ) {
    return null;
  }

  // Need at least one user message to summarize
  const userMessages = (session.messages || []).filter((m: any) => m.role === "user");
  if (userMessages.length < MIN_USER_MESSAGES) {
    return null;
  }

  // ENG-2163: the summary is served to the customer verbatim via the customer-reachable
  // `account_summary` tool, so it must not paraphrase delegated-admin activity. Redact admin
  // tool results + admin-tainted assistant narration from the input first. adminToolNames comes
  // from agentModeService via a lazy import to avoid a static cycle (this file already lazy-imports
  // agentModeService for callLLM below).
  const { redactAdminActivity } = await import("../utils/adminOnlyMessageFilter");
  const { ADMIN_SKILL_TOOL_NAMES } = await import("./agentModeService");
  const redactedMessages = redactAdminActivity(session.messages || [], { adminToolNames: ADMIN_SKILL_TOOL_NAMES });

  const simplifiedMessages = redactedMessages
    .filter((m: any) => m.role === "user" || m.role === "assistant")
    .map((m: any) => ({
      role: m.role,
      content: typeof m.content === "string" ? m.content : JSON.stringify(m.content),
    }));

  // ENG-1858: bill the summary to the session owner instead of "system".
  const result = await summarizeSession(simplifiedMessages, messageCount, {
    userId: session.userId,
    sessionId: session.sessionId,
    feature: meteringFeature("session_summary", session.sessionType, extractScheduleId(session.pageIdentifier)),
  });

  let summaryText = result.summary;
  const toolCallLedger = flattenSessionToolCalls(session.messages);
  // scopeToLastStepBoundary=false (CodeRabbit, this PR): this summary spans the
  // WHOLE session, potentially several already-closed work-plan steps. The default
  // scoping restricts the ledger to activity since the last set_work_plan_status
  // call, which is correct for a single closing turn but would misread a truthful
  // claim about several completed steps' assets as false the moment the currently
  // -open step hasn't produced anything of its own yet.
  //
  // ENG-2076: gated on `assetProducingToolsInPlay(toolCallLedger)` — this check only
  // understands image/video/HTML-template tools (`ASSET_PRODUCING_TOOL_NAMES`), so a
  // session built entirely on a different domain (Meta Ads, CRM, LinkedIn outreach,
  // etc.) always reads `actual: 0` here regardless of what really happened. Without
  // this gate, a Meta Ads session whose LLM-written summary happens to phrase a true
  // result with a digit near an asset noun (the summarizer's own system prompt
  // models exactly that: `"Created 3 LinkedIn posts..."`) would have its accurate
  // summary silently REPLACED by a false "0 of 3... not yet complete" line — worse
  // than the inline chat correction this same bug caused elsewhere, since this one
  // persists to `session.sessionSummary` and is served verbatim by the
  // `account_summary` Emma tool. Unlike the per-turn call site in
  // agentModeService.ts, gating on this SAME whole-session `toolCallLedger` (not a
  // narrower per-turn one) is correct here: `actual` is computed from this identical
  // ledger, so the gate and the count never disagree on scope.
  const falseClaim = assetProducingToolsInPlay(toolCallLedger)
    ? detectFalseCompletionClaim(summaryText, toolCallLedger, false)
    : null;
  if (falseClaim) {
    console.warn(
      `SessionSummary: generated summary for session ${session.sessionId} claims ${falseClaim.claimed} completed ` +
      `but the ledger shows only ${falseClaim.actual} succeeded asset-producing call(s) — using a ledger-grounded summary instead`
    );
    summaryText = `Work in progress — ${falseClaim.actual} of ${falseClaim.claimed} asset(s) confirmed produced so far; not yet complete.`;
  }

  const sessionSummary: NonNullable<ChatSession["sessionSummary"]> = {
    summary: summaryText,
    evaluatedAt: new Date().toISOString(),
    evaluatedMessageIndex: result.evaluatedMessageIndex,
  };

  await chatbotDb.updateSessionSummary(session.sessionId, sessionSummary);

  return sessionSummary;
}
