import type Stripe from 'stripe';

/**
 * Version-tolerant readers for Stripe invoice fields that moved in the Basil
 * API (2025-03-31.basil; we pin 2025-05-28.basil in stripeClientFactory.ts).
 *
 *  - `invoice.subscription` was removed; the subscription that generated an
 *    invoice is now `invoice.parent.subscription_details.subscription`.
 *  - `invoice_line_item.price` was removed; the price is now
 *    `line.pricing.price_details.price` (an id).
 *
 * The SDK pin only governs what our own API calls return. A webhook payload is
 * rendered at the webhook ENDPOINT's API version, which can differ, so every
 * reader takes the Basil field first and falls back to the legacy one.
 *
 * Types are derived from the SDK's Basil types, plus the legacy field, so a real
 * `Stripe.Invoice` / `Stripe.InvoiceLineItem` and an untyped webhook object are
 * both accepted. Expanded objects (`{ id }`) are read as their id.
 */

/** An id field that may be expanded into an object. */
type IdRef = string | { id?: string | null } | null | undefined;

export interface InvoiceSubscriptionSource {
  parent?: {
    subscription_details?: {
      subscription?: Stripe.Invoice.Parent.SubscriptionDetails['subscription'] | IdRef;
    } | null;
  } | null;
  /** Pre-Basil location. */
  subscription?: IdRef;
}

export interface InvoiceLinePriceSource {
  pricing?: {
    price_details?: {
      price?: Stripe.InvoiceLineItem.Pricing.PriceDetails['price'] | IdRef;
    } | null;
  } | null;
  /** Pre-Basil location (an expanded `Stripe.Price`). */
  price?: IdRef;
}

/** The id of a Stripe reference that may be a plain id or an expanded `{ id }` object. */
export function stripeIdOf(ref: unknown): string | null {
  if (typeof ref === 'string') return ref || null;
  if (ref && typeof ref === 'object' && typeof (ref as { id?: unknown }).id === 'string') {
    return (ref as { id: string }).id || null;
  }
  return null;
}

/**
 * The id of the subscription that generated this invoice, or null when it was
 * not generated by a subscription (one-off, quote, or pay-as-you-go invoices).
 */
export function invoiceSubscriptionId(
  invoice: InvoiceSubscriptionSource | null | undefined
): string | null {
  if (!invoice) return null;
  return stripeIdOf(invoice.parent?.subscription_details?.subscription) ?? stripeIdOf(invoice.subscription);
}

/** The price id of an invoice line item, or null when it has none. */
export function invoiceLinePriceId(
  line: InvoiceLinePriceSource | null | undefined
): string | null {
  if (!line) return null;
  return stripeIdOf(line.pricing?.price_details?.price) ?? stripeIdOf(line.price);
}
