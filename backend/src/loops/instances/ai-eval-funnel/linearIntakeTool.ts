/**
 * LinearIntakeTool — turns an ai-eval loop proposal into one canonical Linear issue.
 *
 * The loop is a task producer; Argusoft's Autofix service is the executor. This tool therefore
 * stops at durable, deduped intake. It never launches a second cloud environment.
 */

import type { Mutation, MutationProposal, MutationTools } from '../../core/types';
import { asMutationId } from '../../core/types';
import {
  fileAutoIssue,
  type FileAutoIssueParams,
  type FiledAutoResult,
} from '../../../services/intakeService';
import type { AiEvalProposalPayload } from './rules';
import { aiEvalManifest, AI_EVAL_LOOP_ID } from './manifest';
import { enrichWithRCA, type RcaEnrichment } from './rcaEnricher';

type LoopIssueFiler = (params: FileAutoIssueParams) => Promise<FiledAutoResult>;
type ExecutionRoute = NonNullable<FileAutoIssueParams['executionRoute']>;

interface LinearIntakeToolOptions {
  /** Injected in tests; production uses the canonical Linear intake service. */
  fileIssue?: LoopIssueFiler;
  /** Inject a custom RCA enricher in tests. */
  enricher?: (
    proposal: MutationProposal<AiEvalProposalPayload>,
    mutationSurface: readonly { key: string; kind: string }[],
  ) => Promise<RcaEnrichment>;
}

const AUTOFIX_RULES = new Set(['eval-failing']);

/**
 * Autonomy is explicit and fail-closed. Priority, complexity, `autoShipSafe`, and model confidence
 * do not grant execution authority.
 */
export function executionRouteForAiEvalProposal(
  proposal: MutationProposal<AiEvalProposalPayload>,
): ExecutionRoute {
  if (
    proposal.kind === 'code_change' &&
    AUTOFIX_RULES.has(proposal.sourceRuleId) &&
    proposal.payload.targetKey === 'ai_eval_emma_prompt'
  ) {
    return 'autofix';
  }
  return 'human-triage';
}

export class LinearIntakeTool implements MutationTools<AiEvalProposalPayload> {
  private readonly filer: LoopIssueFiler;
  private readonly enricher: NonNullable<LinearIntakeToolOptions['enricher']>;

  constructor(options: LinearIntakeToolOptions = {}) {
    this.filer = options.fileIssue ?? fileAutoIssue;
    this.enricher = options.enricher ?? enrichWithRCA;
  }

  async apply(proposal: MutationProposal<AiEvalProposalPayload>): Promise<Mutation> {
    const mutationId = asMutationId(`${proposal.proposalId}:mutation`);
    const title = this.buildTitle(proposal);
    const route = executionRouteForAiEvalProposal(proposal);
    const enrichment = await this.enricher(proposal, aiEvalManifest.mutationSurface);
    const body = this.buildBody(proposal, route, enrichment);

    try {
      const filed = await this.filer({
        title,
        description: body,
        source: `${AI_EVAL_LOOP_ID} loop`,
        executionRoute: route,
        notionContext: {
          'Alert Class': `${AI_EVAL_LOOP_ID}:${proposal.sourceRuleId}`,
          'Alert Priority': this.priorityFor(proposal).toLowerCase(),
          'Loop ID': AI_EVAL_LOOP_ID,
          'Rule ID': proposal.sourceRuleId,
          'Proposal ID': proposal.proposalId,
        },
      });
      return {
        mutationId,
        proposalId: proposal.proposalId,
        kind: proposal.kind,
        artifact: {
          linearIssueId: filed.pageId,
          linearUrl: filed.url ?? '',
          title,
          deduped: filed.deduped,
          executionRoute: route,
          rcaEnrichment: enrichment,
        },
      };
    } catch (err) {
      return {
        mutationId,
        proposalId: proposal.proposalId,
        kind: proposal.kind,
        artifact: { title, executionRoute: route, rcaEnrichment: enrichment },
        error: err instanceof Error ? err.message : String(err),
      };
    }
  }

  private buildTitle(proposal: MutationProposal<AiEvalProposalPayload>): string {
    const first = proposal.hypothesis.split(/[.!?]\s/)[0].slice(0, 80);
    return `fix(ai-eval-funnel): ${proposal.sourceRuleId} — ${first}`;
  }

  private priorityFor(proposal: MutationProposal<AiEvalProposalPayload>): 'High' | 'Medium' {
    if (
      proposal.sourceRuleId === 'eval-failing' ||
      proposal.sourceRuleId === 'complaint-received' ||
      proposal.sourceRuleId === 'top-of-funnel-cold' ||
      proposal.sourceRuleId === 'capture-broken'
    ) {
      return 'High';
    }
    return 'Medium';
  }

  private buildBody(
    proposal: MutationProposal<AiEvalProposalPayload>,
    route: ExecutionRoute,
    enrichment: RcaEnrichment,
  ): string {
    const lines: string[] = [
      `**Auto-generated by the ${AI_EVAL_LOOP_ID} closed loop on ${new Date().toISOString()}.**`,
      '',
      '## Summary',
      proposal.hypothesis,
      '',
    ];

    if (enrichment.error) {
      lines.push('## RCA unavailable', enrichment.error, '');
    } else {
      lines.push('## Root cause hypotheses');
      for (const hypothesis of enrichment.topHypotheses) lines.push(`- ${hypothesis}`);
      lines.push('', '## Ranked fixes');
      enrichment.rankedFixes.forEach((fix, index) => {
        lines.push(
          `**${index + 1}. ${fix.title}** — impact: ${fix.impact}, confidence: ${fix.confidence}, ` +
            `cost: ${fix.cost_sp} SP. ${fix.why_this_rank}`,
        );
      });
      lines.push('');
    }

    lines.push(
      '## Triggering data',
      '```json',
      JSON.stringify(proposal.triggeringStats, null, 2),
      '```',
      '',
      '## Proposed change',
      '```json',
      JSON.stringify(proposal.payload, null, 2),
      '```',
      '',
      '## Intake decision',
      route === 'autofix'
        ? 'Autofix: eligible — deterministic code reliability work, fully mockable.'
        : 'Needs PM: not eligible for unattended execution; unknown and behavior-changing work fails closed.',
      '',
      '## Acceptance criteria (system invariant)',
      '1. A regression test reproduces the triggering failure before the fix and passes afterward.',
      '2. The implementation is PURE or MOCKABLE and requires no live third-party credential.',
      '3. The fix does not broaden product behavior beyond the proposed reliability correction.',
      '4. The PR reports deterministic test evidence and stops for repository review gates.',
    );
    return lines.join('\n');
  }
}
