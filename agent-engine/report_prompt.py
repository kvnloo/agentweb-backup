#!/usr/bin/env python3
"""Dependency-light builder for the deep-research HTML report prompt.

Kept free of heavy imports (autogen, nest_asyncio, langchain, task_utils) so the
prompt text — including the ENG-351 inline-source-citation instruction — can be
unit-tested offline without spinning up the full agent-engine runtime.
"""

# ENG-351: every quoted figure in the generated research report must carry its
# source inline, immediately next to the number, matching the Claude/Gemini
# citation style — never aggregated only in a bottom references section, and
# never fabricated when a figure has no traceable source.
INLINE_CITATION_INSTRUCTION = (
    "Cite the source of every quoted number, statistic, or data point INLINE — "
    "immediately next to the figure it supports (a linked source or a parenthetical "
    "attribution), matching the Claude/Gemini inline-citation style — rather than "
    "collecting sources only in a separate references section at the end. Only use "
    "sources actually present in the research log; if a figure has no traceable "
    "source, do not fabricate one."
)


def build_report_format_prompt(query: str, log_for_prompt: str) -> str:
    """Build the LLM prompt that turns a research log into a self-contained HTML report."""
    return f"""
            You are a professional research report generator. Your task is to create a complete, self-contained HTML document
            that presents the research findings in a visually appealing and professional format.

            The research was conducted on the following query: "{query}"

            IMPORTANT INSTRUCTIONS:
            1. Generate a COMPLETE HTML document including <!DOCTYPE html>, <html>, <head>, <body> tags, and embedded CSS.
            2. The report should be visually appealing with professional styling.
            3. Extract the initial research summary from the end of the log and use it as a foundation.
            4. Enrich this summary with additional details from other parts of the log such as detailed descriptions,data tables, charts, etc.
            5. Make the report as comprehensive and detailed as possible.
            6. Use a clean, professional color scheme.
            7. Ensure the report is well-structured with clear headings and sections.
            8. Do not include any other text such as ```html or ``` in your response than the HTML document.
            9. Add disclaimer that "The research report is generated by an AI. It may contain errors or inaccuracies. Please use with caution."
            10. {INLINE_CITATION_INSTRUCTION}

            Here is the research log to analyze:
            {log_for_prompt}
            """
